// Package gen is the generator behind the tether command: it reads the Go
// program, finds every tether.Route, and writes the OpenAPI document, the
// TypeScript client and the enum registrations.
package gen

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/maulai/tether/internal/jsregex"
	"github.com/maulai/tether/internal/vtag"
)

// Options configure one run.
type Options struct {
	Dir      string   // where the package patterns are resolved
	Patterns []string // package patterns, ./... when empty
	Out      string   // directory for the TypeScript files
	OpenAPI  string   // path of the OpenAPI document
	Title    string   // OpenAPI info.title
	Version  string   // OpenAPI info.version
	Tool     string   // tether's own version, named in file headers
}

// File is one output. Data nil means the file must not exist.
type File struct {
	Path string
	Data []byte
}

// Generate computes every output without writing anything.
func Generate(o Options) ([]File, error) {
	if len(o.Patterns) == 0 {
		o.Patterns = []string{"./..."}
	}
	if o.Out == "" {
		return nil, errors.New("no output directory; pass -out")
	}
	if o.OpenAPI == "" {
		o.OpenAPI = "openapi.json"
	}
	if o.Title == "" {
		o.Title = "API"
	}
	if o.Version == "" {
		o.Version = "unversioned"
	}
	p, err := load(o.Dir, o.Patterns)
	if err != nil {
		return nil, err
	}
	if len(p.routes) == 0 && len(p.errs) == 0 {
		return nil, errors.New("no tether.Route call found in " + strings.Join(o.Patterns, " "))
	}
	jsPatterns := map[string]string{}
	for name, pt := range p.patterns {
		if !vtag.IsName(name) || vtag.Builtin[name] {
			p.errorf(0, "%q cannot name a rule", name)
			continue
		}
		js, err := jsregex.Translate(pt.expr)
		if err != nil {
			p.errorf(0, "pattern %s: %v", name, err)
			continue
		}
		jsPatterns[name] = js
	}
	m := newModel(p)
	if len(p.errs) > 0 {
		sort.Strings(p.errs)
		return nil, fmt.Errorf("%d problem(s):\n  %s", len(p.errs), strings.Join(dedupe(p.errs), "\n  "))
	}

	header := "// Code generated by tether; DO NOT EDIT."
	if release.MatchString(o.Tool) {
		header = "// Code generated by tether " + o.Tool + "; DO NOT EDIT."
	}
	abs := func(path string) string {
		if filepath.IsAbs(path) {
			return path
		}
		return filepath.Join(o.Dir, path)
	}
	files := []File{
		{Path: abs(o.OpenAPI), Data: m.renderOpenAPI(o.Title, o.Version)},
		{Path: abs(filepath.Join(o.Out, "index.ts")), Data: m.renderIndex(header)},
		{Path: abs(filepath.Join(o.Out, "runtime.ts")), Data: renderRuntime(header, messageTable(p.patterns, p.messages), jsPatterns, p.checks)},
	}
	files = append(files, m.renderGoFiles(header)...)
	return files, nil
}

// release matches a tagged version. A development build carries a pseudo
// version that changes with every commit; naming it in headers would make
// every file differ after each commit.
var release = regexp.MustCompile(`^v\d+\.\d+\.\d+(-[0-9A-Za-z.]+)?$`)

func dedupe(s []string) []string {
	var out []string
	for i, x := range s {
		if i == 0 || x != s[i-1] {
			out = append(out, x)
		}
	}
	return out
}

// Write writes the files, creating directories, and removes the ones whose
// Data is nil.
func Write(files []File) error {
	for _, f := range files {
		if f.Data == nil {
			if err := os.Remove(f.Path); err != nil && !errors.Is(err, os.ErrNotExist) {
				return err
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(f.Path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(f.Path, f.Data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// Stale lists the files that differ from what Generate computed: missing,
// changed, or present although they should not exist.
func Stale(files []File) []string {
	var out []string
	for _, f := range files {
		cur, err := os.ReadFile(f.Path)
		switch {
		case f.Data == nil && err == nil:
			out = append(out, f.Path+" (should not exist)")
		case f.Data != nil && err != nil:
			out = append(out, f.Path+" (missing)")
		case f.Data != nil && !bytes.Equal(cur, f.Data):
			out = append(out, f.Path)
		}
	}
	return out
}
