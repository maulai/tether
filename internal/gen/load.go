const (
	tetherPath = "github.com/maulai/tether"
	genFile    = "tether_gen.go"
	genPrefix  = "// Code generated by tether" // how tether knows its own files
)

// program is what the generator reads from the source: the routes, the
// project's rules and messages, and the declarations it needs for names and
// comments.
type program struct {
	fset     *token.FileSet
	pkgs     []*packages.Package
	roots    map[*types.Package]*packages.Package
	funcDocs map[*types.Func]string
	typeDocs map[*types.TypeName]string
	varDocs  map[*types.Var]string // fields and package variables
	varInits map[*types.Var]ast.Expr
	initVars map[ast.Expr]*types.Var // the variable a package level value initialises
	infoOf   map[*ast.File]*types.Info

	routes    []*route
	validates []validateCall
	patterns  map[string]pattern         // by rule name, a Format's included
	formats   map[*types.TypeName]string // the rule name of each Format
	checks    []string
	messages  map[string]string      // nil: no Messages call
	problems  map[string]*problemDef // by code
	auths     map[*types.Var]*authDef
	errs      []string
}

// problemDef is one tether.Problem literal with a code.
type problemDef struct {
	code    string
	status  int
	message string // empty when it is not a constant
	doc     string
	pos     token.Pos
}

// authDef is one tether.Auth, declared as a package variable.
type authDef struct {
	name   string // the variable's name, the scheme's name in OpenAPI
	doc    string
	cookie string
	header string
	bearer bool
	pos    token.Pos
}

// carrier names where the credential of a travels, to tell two Auths of
// one route apart; it matches the text of tether's own check.
func (a *authDef) carrier() string {
	if a.cookie != "" {
		return "the cookie " + a.cookie
	}
	name := "Authorization"
	if a.header != "" {
		name = textproto.CanonicalMIMEHeaderKey(a.header)
	}
	return "the header " + name
}

// access is what a route's Options say about who may call it.
type access struct {
	auths  []*authDef // the ways in, in order; none for a public route
	scopes []string
	public bool
}

// validateCall is one tether.Validate call: the type of its argument and
// the package that makes it, which registers the enums of that type.
type validateCall struct {
	pkg *types.Package
	typ types.Type
	pos token.Pos
}

// pattern is one tether.Pattern call.
type pattern struct {
	expr    string // Go regular expression
	message string // the text for a value that does not match
}

type route struct {
	pos     token.Position
	method  string
	path    string
	params  []pathParam
	handler *types.Func
	name    string // TypeScript function name
	doc     string
	in      types.Type // nil without input
	out     types.Type // nil without output
	upload  bool
	file    bool
	query   bool
	access  access
}

type pathParam struct {
	name     string
	wildcard bool
	typ      types.Type // the handler's argument
	pos      token.Pos
}

func (p *program) errorf(pos token.Pos, format string, args ...any) {
	where := ""
	if pos.IsValid() {
		where = p.fset.Position(pos).String() + ": "
	}
	p.errs = append(p.errs, where+fmt.Sprintf(format, args...))
}

func load(dir string, patterns []string) (*program, error) {
	cfg := &packages.Config{
		Fset: token.NewFileSet(),
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo | packages.NeedImports | packages.NeedModule,
		Dir: dir,
		// A stale tether_gen.go may name constants that no longer exist; the
		// generator reads the program without it and writes a new one. A file
		// of that name that tether did not write is read as it is.
		ParseFile: func(fset *token.FileSet, filename string, src []byte) (*ast.File, error) {
			f, err := parser.ParseFile(fset, filename, src, parser.ParseComments)
			if f != nil && filepath.Base(filename) == genFile && bytes.HasPrefix(src, []byte(genPrefix)) {
				f.Decls, f.Imports = nil, nil
			}
			return f, err
		},
	}
	pkgs, err := packages.Load(cfg, patterns...)
	if err != nil {
		return nil, err
	}
	p := &program{
		fset:     cfg.Fset,
		pkgs:     pkgs,
		roots:    map[*types.Package]*packages.Package{},
		funcDocs: map[*types.Func]string{},
		typeDocs: map[*types.TypeName]string{},
		varDocs:  map[*types.Var]string{},
		varInits: map[*types.Var]ast.Expr{},
		initVars: map[ast.Expr]*types.Var{},
		infoOf:   map[*ast.File]*types.Info{},
		patterns: map[string]pattern{},
		formats:  map[*types.TypeName]string{},
		problems: map[string]*problemDef{},
		auths:    map[*types.Var]*authDef{},
	}
	var loadErrs []string
	for _, pkg := range pkgs {
		for _, e := range pkg.Errors {
			// The go command compiles packages as they are on disk, a stale
			// tether_gen.go included, and reports what no longer compiles;
			// the generator itself reads them without that file.
			if strings.Contains(e.Pos, genFile) || strings.Contains(e.Msg, genFile) {
				continue
			}
			loadErrs = append(loadErrs, e.Error())
		}
	}
	if len(loadErrs) > 0 {
		return nil, fmt.Errorf("the program does not compile:\n  %s", strings.Join(loadErrs, "\n  "))
	}
	for _, pkg := range pkgs {
		p.roots[pkg.Types] = pkg
		for _, f := range pkg.Syntax {
			p.infoOf[f] = pkg.TypesInfo
			p.index(pkg.TypesInfo, f)
		}
	}
	for _, pkg := range pkgs {
		for _, f := range pkg.Syntax {
			p.scan(pkg.Types, pkg.TypesInfo, f)
		}
	}
	sort.Slice(p.routes, func(i, j int) bool {
		a, b := p.routes[i], p.routes[j]
		if a.path != b.path {
			return a.path < b.path
		}
		return methodOrder(a.method) < methodOrder(b.method)
	})
	return p, nil
}

func methodOrder(m string) int {
	return strings.Index("GET POST PUT PATCH DELETE", m)
}

// index records doc comments and variable initialisers by object, so later
// steps can find them from types alone.
func (p *program) index(info *types.Info, f *ast.File) {
	for _, decl := range f.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if fn, ok := info.Defs[d.Name].(*types.Func); ok {
				p.funcDocs[fn] = strings.TrimSpace(d.Doc.Text())
			}
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					doc := s.Doc
					if doc == nil && len(d.Specs) == 1 {
						doc = d.Doc
					}
					if tn, ok := info.Defs[s.Name].(*types.TypeName); ok {
						p.typeDocs[tn] = strings.TrimSpace(doc.Text())
					}
				case *ast.ValueSpec:
					doc := s.Doc
					if doc == nil && len(d.Specs) == 1 {
						doc = d.Doc
					}
					for i, name := range s.Names {
						v, ok := info.Defs[name].(*types.Var)
						if !ok {
							continue
						}
						p.varDocs[v] = strings.TrimSpace(doc.Text())
						if i < len(s.Values) {
							p.varInits[v] = s.Values[i]
							p.initVars[ast.Unparen(s.Values[i])] = v
						}
					}
				}
			}
		}
	}
	ast.Inspect(f, func(n ast.Node) bool {
		st, ok := n.(*ast.StructType)
		if !ok {
			return true
		}
		for _, field := range st.Fields.List {
			doc := field.Doc
			if doc == nil {
				doc = field.Comment
			}
			for _, name := range field.Names {
				if v, ok := info.Defs[name].(*types.Var); ok {
					p.varDocs[v] = strings.TrimSpace(doc.Text())
				}
			}
		}
		return true
	})
}

// scan finds the calls into tether that the generator must read.
func (p *program) scan(pkg *types.Package, info *types.Info, f *ast.File) {
	ast.Inspect(f, func(n ast.Node) bool {
		if lit, ok := n.(*ast.CompositeLit); ok && isTether(info.TypeOf(lit), "Problem") {
			p.problem(info, lit)
			return true
		}
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		fn := callee(info, call)
		if fn == nil || fn.Pkg() == nil || fn.Pkg().Path() != tetherPath {
			return true
		}
		switch fn.Name() {
		case "Route":
			p.route(info, call)
		case "Pattern":
			name, ok1 := p.constString(info, call.Args[0])
			expr, ok2 := p.constString(info, call.Args[1])
			msg, ok3 := p.ruleMessage(info, call.Args[2], name)
			if ok1 && ok2 && ok3 {
				if _, dup := p.patterns[name]; dup {
					p.errorf(call.Pos(), "rule %s registered twice", name)
				}
				p.patterns[name] = pattern{expr: expr, message: msg}
			}
		case "Format":
			p.format(info, call)
		case "Check":
			// The browser never reports a Check, so its message stays on the
			// server; it is read only to catch what the server rejects.
			name, ok := p.constString(info, call.Args[0])
			p.ruleMessage(info, call.Args[2], name)
			if ok {
				p.checks = append(p.checks, name)
			}
		case "Messages":
			p.readMessages(info, call)
		case "Validate":
			if len(call.Args) == 1 {
				p.validates = append(p.validates, validateCall{pkg: pkg, typ: info.TypeOf(call.Args[0]), pos: call.Args[0].Pos()})
			}
		}
		return true
	})
}

func callee(info *types.Info, call *ast.CallExpr) *types.Func {
	var id *ast.Ident
	switch fun := ast.Unparen(call.Fun).(type) {
	case *ast.Ident:
		id = fun
	case *ast.SelectorExpr:
		id = fun.Sel
	case *ast.IndexExpr:
		if sel, ok := fun.X.(*ast.SelectorExpr); ok {
			id = sel.Sel
		}
	}
	if id == nil {
		return nil
	}
	fn, _ := info.Uses[id].(*types.Func)
	return fn
}

func (p *program) constString(info *types.Info, e ast.Expr) (string, bool) {
	tv, ok := info.Types[e]
	if !ok || tv.Value == nil || tv.Value.Kind() != constant.String {
		p.errorf(e.Pos(), "this argument must be a string constant, so tether can read it")
		return "", false
	}
	return constant.StringVal(tv.Value), true
}

// ruleMessage reads the message of a project rule, which must not be empty,
// as the server insists at start-up.
func (p *program) ruleMessage(info *types.Info, e ast.Expr, name string) (string, bool) {
	msg, ok := p.constString(info, e)
	if ok && msg == "" {
		p.errorf(e.Pos(), "rule %s needs a message", name)
		return "", false
	}
	return msg, ok
}

func (p *program) route(info *types.Info, call *ast.CallExpr) {
	pattern, ok := p.constString(info, call.Args[0])
	if !ok {
		return
	}
	method, path, _ := strings.Cut(pattern, " ")
	path = strings.TrimSpace(path)
	r := &route{pos: p.fset.Position(call.Pos()), method: method, path: path}
	switch method {
	case "GET", "POST", "PUT", "PATCH", "DELETE":
	default:
		p.errorf(call.Pos(), "%q: the pattern must start with GET, POST, PUT, PATCH or DELETE", pattern)
		return
	}
	if !strings.HasPrefix(path, "/") {
		p.errorf(call.Pos(), "%q: the path must start with /", pattern)
		return
	}
	r.query = method == "GET" || method == "DELETE"
	r.params = pathParams(path)

	switch h := ast.Unparen(call.Args[1]).(type) {
	case *ast.Ident:
		r.handler, _ = info.Uses[h].(*types.Func)
	case *ast.SelectorExpr:
		if sel := info.Selections[h]; sel != nil {
			if sel.Kind() == types.MethodVal {
				r.handler, _ = sel.Obj().(*types.Func)
			}
		} else {
			r.handler, _ = info.Uses[h.Sel].(*types.Func)
		}
	}
	if r.handler == nil {
		p.errorf(call.Args[1].Pos(), "the handler must be a named function or method, so tether can name the TypeScript function after it")
		return
	}
	r.name = lowerCamel(r.handler.Name())
	r.doc = p.funcDocs[r.handler.Origin()]

	sig := r.handler.Type().(*types.Signature)
	params, results := sig.Params(), sig.Results()
	shapeErr := func() {
		p.errorf(call.Args[1].Pos(), "%s must have the shape %s", r.handler.Name(), shape)
	}
	if params.Len() < 1 || sig.Variadic() || types.TypeString(params.At(0).Type(), nil) != "*net/http.Request" {
		shapeErr()
		return
	}
	errType := types.Universe.Lookup("error").Type()
	switch {
	case results.Len() == 1 && types.Identical(results.At(0).Type(), errType):
	case results.Len() == 2 && types.Identical(results.At(1).Type(), errType):
		r.out = results.At(0).Type()
		r.file = isTether(r.out, "File")
	default:
		shapeErr()
		return
	}
	extra := params.Len() - 1 - len(r.params)
	if extra < 0 || extra > 1 {
		p.errorf(call.Args[1].Pos(), "%s: the pattern has %d path parameter(s), %s; the handler takes them after r, in order, then its input: %s",
			r.handler.Name(), len(r.params), paramList(r.params), shape)
		return
	}
	for i := range r.params {
		pp := &r.params[i]
		v := params.At(1 + i)
		pp.typ, pp.pos = v.Type(), v.Pos()
		if v.Name() != "" && v.Name() != "_" && v.Name() != pp.name {
			p.errorf(v.Pos(), "%s: parameter %s stands where the pattern has {%s}; name it %s, or _ when the handler does not need it", r.handler.Name(), v.Name(), pp.name, pp.name)
		}
	}
	if len(call.Args) > 2 {
		r.access = p.options(info, call)
	}
	if extra == 1 {
		r.in = params.At(params.Len() - 1).Type()
		switch {
		case isTether(r.in, "Upload"):
			if r.query {
				p.errorf(call.Pos(), "%s: an upload needs POST, PUT or PATCH", r.handler.Name())
				return
			}
			r.upload = true
		default:
			if _, ok := r.in.Underlying().(*types.Struct); !ok || isPointer(r.in) {
				p.errorf(call.Args[1].Pos(), "%s: the input must be a struct, not %s", r.handler.Name(), r.in)
				return
			}
		}
	}
	p.routes = append(p.routes, r)
}

const shape = "func(r *http.Request[, path parameters][, in In]) ([Out, ]error)"

func paramList(params []pathParam) string {
	if len(params) == 0 {
		return "none"
	}
	names := make([]string, len(params))
	for i, pp := range params {
		names[i] = "{" + pp.name + "}"
	}
	return strings.Join(names, ", ")
}

// options reads the Options of a route: a tether.Options literal in the
// call or a package variable initialised with one.
func (p *program) options(info *types.Info, call *ast.CallExpr) access {
	var a access
	if len(call.Args) > 3 || call.Ellipsis.IsValid() {
		p.errorf(call.Args[2].Pos(), "pass one tether.Options to Route, directly")
		return a
	}
	lit, linfo := p.literal(info, call.Args[2], "Options")
	if lit == nil {
		p.errorf(call.Args[2].Pos(), "the Options must be a tether.Options literal or a package variable initialised with one, so tether can read them")
		return a
	}
	var one ast.Expr  // the Auth field
	var many ast.Expr // the Auths field
	for _, el := range lit.Elts {
		kv, ok := el.(*ast.KeyValueExpr)
		key, _ := kv.Key.(*ast.Ident)
		if !ok || key == nil {
			p.errorf(el.Pos(), "name the fields of tether.Options")
			continue
		}
		switch key.Name {
		case "Auth":
			one = kv.Value
			if auth := p.auth(linfo, kv.Value); auth != nil {
				a.auths = append(a.auths, auth)
			}
		case "Auths":
			many = kv.Value
			a.auths = append(a.auths, p.authList(linfo, kv.Value)...)
		case "Scopes":
			a.scopes = p.stringList(linfo, kv.Value)
		case "Public":
			tv := linfo.Types[kv.Value]
			if tv.Value == nil || tv.Value.Kind() != constant.Bool {
				p.errorf(kv.Value.Pos(), "Public must be a constant, so tether can read it")
				continue
			}
			a.public = constant.BoolVal(tv.Value)
		}
	}
	switch {
	case one != nil && many != nil:
		p.errorf(lit.Pos(), "a route has an Auth or Auths, not both")
	case a.public && (one != nil || many != nil):
		p.errorf(lit.Pos(), "a route is either Public or has an Auth, not both")
	case len(a.scopes) > 0 && one == nil && many == nil:
		p.errorf(lit.Pos(), "Scopes need an Auth that checks them")
	}
	return a
}

// authList reads the alternatives of Auths: two or more package variables,
// each read from a place of its own, since the credential a request
// carries picks the one tether checks.
func (p *program) authList(info *types.Info, e ast.Expr) []*authDef {
	lit, ok := ast.Unparen(e).(*ast.CompositeLit)
	if !ok {
		p.errorf(e.Pos(), "Auths must be a []tether.Auth literal, so tether can read them")
		return nil
	}
	if len(lit.Elts) < 2 {
		p.errorf(lit.Pos(), "Auths are alternatives and need two or more; for one way in, use Auth")
	}
	var out []*authDef
	for _, el := range lit.Elts {
		a := p.auth(info, el)
		if a == nil {
			continue
		}
		for _, prev := range out {
			if prev == a {
				p.errorf(el.Pos(), "Auths names %s twice", a.name)
				break
			}
			if prev.carrier() == a.carrier() {
				p.errorf(el.Pos(), "%s and %s both read %s; tether could not tell which one a request carries", prev.name, a.name, a.carrier())
				break
			}
		}
		out = append(out, a)
	}
	return out
}

// literal finds the composite literal of the tether type name that e is or
// that the package variable e names was initialised with, and the type
// information of the package it is written in.
func (p *program) literal(info *types.Info, e ast.Expr, name string) (*ast.CompositeLit, *types.Info) {
	e = ast.Unparen(e)
	if lit, ok := e.(*ast.CompositeLit); ok && isTether(info.TypeOf(lit), name) {
		return lit, info
	}
	v := p.varOf(info, e)
	if v == nil {
		return nil, nil
	}
	lit, ok := ast.Unparen(p.varInits[v]).(*ast.CompositeLit)
	vinfo := p.infoFor(v)
	if !ok || vinfo == nil || !isTether(vinfo.TypeOf(lit), name) {
		return nil, nil
	}
	return lit, vinfo
}

func (p *program) varOf(info *types.Info, e ast.Expr) *types.Var {
	var id *ast.Ident
	switch x := ast.Unparen(e).(type) {
	case *ast.Ident:
		id = x
	case *ast.SelectorExpr:
		id = x.Sel
	default:
		return nil
	}
	v, _ := info.Uses[id].(*types.Var)
	if v == nil || v.Pkg() == nil || v.Parent() != v.Pkg().Scope() {
		return nil // not a package variable
	}
	return v
}

// auth reads the Auth an Options names. It must be a package variable: its
// name is the scheme's name in OpenAPI.
func (p *program) auth(info *types.Info, e ast.Expr) *authDef {
	v := p.varOf(info, e)
	if v == nil {
		p.errorf(e.Pos(), "declare the Auth as a package variable and name it here; its name names it in OpenAPI")
		return nil
	}
	if a, ok := p.auths[v]; ok {
		return a
	}
	lit, linfo := p.literal(info, e, "Auth")
	if lit == nil {
		p.errorf(e.Pos(), "%s must be initialised with a tether.Auth literal, so tether can read it", v.Name())
		return nil
	}
	a := &authDef{name: v.Name(), doc: p.varDocs[v], pos: v.Pos()}
	p.auths[v] = a
	carriers := 0
	for _, el := range lit.Elts {
		kv, ok := el.(*ast.KeyValueExpr)
		key, _ := kv.Key.(*ast.Ident)
		if !ok || key == nil {
			p.errorf(el.Pos(), "name the fields of tether.Auth")
			continue
		}
		switch key.Name {
		case "Cookie", "Header":
			s, ok := p.constString(linfo, kv.Value)
			if ok && s != "" {
				carriers++
				if key.Name == "Cookie" {
					a.cookie = s
				} else {
					a.header = s
				}
			}
		case "Bearer":
			tv := linfo.Types[kv.Value]
			if tv.Value == nil || tv.Value.Kind() != constant.Bool {
				p.errorf(kv.Value.Pos(), "Bearer must be a constant, so tether can read it")
			} else if constant.BoolVal(tv.Value) {
				carriers++
				a.bearer = true
			}
		}
	}
	if carriers != 1 {
		p.errorf(lit.Pos(), "%s: an Auth names exactly one of Cookie, Header and Bearer", v.Name())
	}
	return a
}

func (p *program) stringList(info *types.Info, e ast.Expr) []string {
	lit, ok := ast.Unparen(e).(*ast.CompositeLit)
	if !ok {
		if id, isIdent := ast.Unparen(e).(*ast.Ident); isIdent && id.Name == "nil" {
			return nil
		}
		p.errorf(e.Pos(), "Scopes must be a []string literal, so tether can read them")
		return nil
	}
	var out []string
	for _, el := range lit.Elts {
		if s, ok := p.constString(info, el); ok {
			out = append(out, s)
		}
	}
	return out
}

var problemCode = regexp.MustCompile(`^[a-z][A-Za-z0-9]*$`)

// problem reads a tether.Problem literal. One with a code is a case the
// client recognises; it is declared once.
func (p *program) problem(info *types.Info, lit *ast.CompositeLit) {
	fields := map[string]ast.Expr{}
	for i, el := range lit.Elts {
		if kv, ok := el.(*ast.KeyValueExpr); ok {
			if key, ok := kv.Key.(*ast.Ident); ok {
				fields[key.Name] = kv.Value
			}
		} else if i < 3 {
			fields[[]string{"Status", "Code", "Message"}[i]] = el
		}
	}
	codeExpr, ok := fields["Code"]
	if !ok {
		return // a Problem without a code is a Fail
	}
	code, ok := p.constString(info, codeExpr)
	if !ok || code == "" {
		return
	}
	d := &problemDef{code: code, pos: lit.Pos()}
	if v := p.initVars[lit]; v != nil {
		d.doc = p.varDocs[v]
	}
	if !problemCode.MatchString(code) {
		p.errorf(codeExpr.Pos(), "problem code %q must be lowerCamel, like mfaRequired, so the client can name a function after it", code)
		return
	}
	tv := info.Types[fields["Status"]]
	if fields["Status"] == nil || tv.Value == nil || tv.Value.Kind() != constant.Int {
		p.errorf(lit.Pos(), "problem %s needs a constant Status, so tether can read it", code)
		return
	}
	status, _ := constant.Int64Val(tv.Value)
	if status < 400 || status > 599 {
		p.errorf(fields["Status"].Pos(), "problem %s: status %d is not an error status", code, status)
		return
	}
	d.status = int(status)
	if m := fields["Message"]; m != nil {
		if tv := info.Types[m]; tv.Value != nil && tv.Value.Kind() == constant.String {
			d.message = constant.StringVal(tv.Value)
		}
	}
	if prev, dup := p.problems[code]; dup {
		p.errorf(lit.Pos(), "problem code %s is declared twice, also at %s; declare it once and use With for another text", code, p.fset.Position(prev.pos))
		return
	}
	p.problems[code] = d
}

// format reads a tether.Format call: a rule like a Pattern, bound to the
// type of its type argument.
func (p *program) format(info *types.Info, call *ast.CallExpr) {
	var id *ast.Ident
	if ix, ok := ast.Unparen(call.Fun).(*ast.IndexExpr); ok {
		switch x := ix.X.(type) {
		case *ast.SelectorExpr:
			id = x.Sel
		case *ast.Ident:
			id = x
		}
	}
	inst, ok := info.Instances[id]
	if id == nil || !ok || inst.TypeArgs.Len() != 1 {
		p.errorf(call.Pos(), "write the type of a Format explicitly, tether.Format[T]")
		return
	}
	named, ok := types.Unalias(inst.TypeArgs.At(0)).(*types.Named)
	if !ok {
		p.errorf(call.Pos(), "a Format needs a named type with UnmarshalText, not %s", inst.TypeArgs.At(0))
		return
	}
	name, ok1 := p.constString(info, call.Args[0])
	expr, ok2 := p.constString(info, call.Args[1])
	msg, ok3 := p.ruleMessage(info, call.Args[2], name)
	if !ok1 || !ok2 || !ok3 {
		return
	}
	if _, dup := p.patterns[name]; dup {
		p.errorf(call.Pos(), "rule %s registered twice", name)
	}
	if prev, dup := p.formats[named.Obj()]; dup {
		p.errorf(call.Pos(), "%s has two formats, %s and %s", named.Obj().Name(), prev, name)
	}
	p.patterns[name] = pattern{expr: expr, message: msg}
	p.formats[named.Obj()] = name
}

func isTether(t types.Type, name string) bool {
	n, ok := types.Unalias(t).(*types.Named)
	return ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == tetherPath && n.Obj().Name() == name
}

func isPointer(t types.Type) bool {
	_, ok := types.Unalias(t).(*types.Pointer)
	return ok
}

func pathParams(path string) []pathParam {
	var out []pathParam
	for {
		i := strings.Index(path, "{")
		if i < 0 {
			return out
		}
		j := strings.Index(path[i:], "}")
		if j < 0 {
			return out
		}
		name := path[i+1 : i+j]
		path = path[i+j+1:]
		if name == "$" {
			continue
		}
		wild := strings.HasSuffix(name, "...")
		out = append(out, pathParam{name: strings.TrimSuffix(name, "..."), wildcard: wild})
	}
}

// readMessages reads the one Messages call. Its arguments are map literals
// or package variables initialised with one; the German table that ships
// with tether is known to the generator directly.
func (p *program) readMessages(info *types.Info, call *ast.CallExpr) {
	if p.messages != nil {
		p.errorf(call.Pos(), "Messages is called more than once; call it in one place")
		return
	}
	p.messages = map[string]string{}
	for _, arg := range call.Args {
		table, ok := p.messageTable(info, arg)
		if !ok {
			p.errorf(arg.Pos(), "an argument of Messages must be a map literal or a package variable initialised with one")
			continue
		}
		for k, v := range table {
			p.messages[k] = v
		}
	}
}

func (p *program) messageTable(info *types.Info, e ast.Expr) (map[string]string, bool) {
	e = ast.Unparen(e)
	if lit, ok := e.(*ast.CompositeLit); ok {
		return p.mapLiteral(info, lit)
	}
	var id *ast.Ident
	switch x := e.(type) {
	case *ast.Ident:
		id = x
	case *ast.SelectorExpr:
		id = x.Sel
	default:
		return nil, false
	}
	v, ok := info.Uses[id].(*types.Var)
	if !ok || v.Pkg() == nil {
		return nil, false
	}
	if v.Pkg().Path() == tetherPath+"/messages/de" && v.Name() == "Messages" {
		return de.Messages, true
	}
	init, ok := p.varInits[v]
	if !ok {
		return nil, false
	}
	lit, ok := ast.Unparen(init).(*ast.CompositeLit)
	if !ok {
		return nil, false
	}
	return p.mapLiteral(p.infoFor(v), lit)
}

func (p *program) infoFor(v *types.Var) *types.Info {
	if pkg := p.roots[v.Pkg()]; pkg != nil {
		return pkg.TypesInfo
	}
	return nil
}

func (p *program) mapLiteral(info *types.Info, lit *ast.CompositeLit) (map[string]string, bool) {
	if info == nil {
		return nil, false
	}
	out := map[string]string{}
	for _, el := range lit.Elts {
		kv, ok := el.(*ast.KeyValueExpr)
		if !ok {
			return nil, false
		}
		k, ok1 := p.constString(info, kv.Key)
		v, ok2 := p.constString(info, kv.Value)
		if !ok1 || !ok2 {
			return nil, false
		}
		out[k] = v
	}
	return out, true
}

// lowerCamel turns a Go name into a TypeScript one: the leading capitals
// become lower case, except the last one when it starts the next word
// (CreateTask: createTask, HTTPGet: httpGet, ID: id).
func lowerCamel(s string) string {
	r := []rune(s)
	n := 0
	for n < len(r) && r[n] >= 'A' && r[n] <= 'Z' {
		n++
	}
	switch {
	case n == 0:
		return s
	case n == len(r):
		return strings.ToLower(s)
	case n > 1:
		n--
	}
	return strings.ToLower(string(r[:n])) + string(r[n:])
}

// projectRule reports whether name is a rule the project registered.
func (p *program) projectRule(name string) bool {
	if _, ok := p.patterns[name]; ok {
		return true
	}
	for _, c := range p.checks {
		if c == name {
			return true
		}
	}
	return false
}
